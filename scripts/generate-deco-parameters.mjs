#!/usr/bin/env node
// 从仓库级参数表生成 deco.charm 的四份消费物，**就地改写仓库里的文件**。
//
// 参数表 config/deco-charm-parameters.json 是 deco 段数值事实的唯一来源；
// #283 的段注册表仍只登记 deco 段本身，不在注册表里另抄 12 个参数。
// 本生成器改写这四个既有文件（不存在 *.generated.ts 旁路文件）：
//   1. backend/conf/conf_deco.go —— 整文件生成（后端常量、字段标签与归一化表）
//   2. backend/config/site_default_settings.yaml —— 只替换 deco 段生成区
//   3. frontend/app/utils/decoCharm.ts —— 只替换 GENERATED DECO 区（读者站常量/元数据）
//   4. frontend_admin/app/utils/decoParams.ts —— 只替换 GENERATED DECO 区（后台常量/元数据）
//   5. 契约（开放接口契约）不在这里生成：先 make openapi，再由
//      scripts/decorate-deco-contract.mjs 从同一参数表注入 min/max/default，
//      最后两端各自 pnpm openapi:types 派生类型。
//
// 产出必须与 gofmt 逐字一致（否则 `gofmt -l backend` 会红），所以 Go 源码里的
// 常量块、结构体字段与复合字面量在这里就按列对齐，不指望事后跑一次 gofmt。
//
// 用法：node scripts/generate-deco-parameters.mjs [--check] [--root <dir>]
//   --check 重新生成到内存并对上面四个文件的对应区域逐字比对；还核对后端 HTTP 行为所需的
//   默认值与契约中的 12 组 min/max/default。不改文件，漂移时退出码非 0。
import { spawnSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const defaultRoot = path.resolve(here, '..');

function args(argv) {
  const out = { check: false, root: defaultRoot };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--check') out.check = true;
    else if (argv[i] === '--root') out.root = path.resolve(argv[++i]);
    else throw new Error(`未知参数 ${argv[i]}`);
  }
  return out;
}

const num = value => String(value);
const goFloat = value => Number.isInteger(value) ? `${value}.0` : num(value);
const goName = (p, suffix) => `Charm${p.go}${suffix}`;
const tsReaderName = (p, suffix) => `CHARM_${p.reader}_${suffix}`;
const tsAdminName = (p, suffix) => `DECO_${p.admin}_${suffix}`;
const adminParamName = p => `DECO_${p.admin}_PARAM`;

// alignRows 复刻 gofmt 对连续单行元素的列对齐：除最后一列外，每列按该列最宽
// 的单元格右侧补空格，列之间一个空格。只在没有空行的连续块内对齐 —— 与 gofmt 的
// tabwriter 分组规则一致。
function alignRows(rows) {
  const widths = [];
  for (const row of rows) {
    for (let i = 0; i < row.length - 1; i++) {
      widths[i] = Math.max(widths[i] || 0, row[i].length);
    }
  }
  return rows.map(row =>
    row.map((cell, i) => (i === row.length - 1 ? cell : cell.padEnd(widths[i]))).join(' '));
}

function backendSource(table) {
  // 常量块：gofmt 把 36 行 `Name = value` 当成一个对齐组，列宽取最长的名字。
  const constants = alignRows(table.parameters.flatMap(p => [
    [goName(p, 'Min'), `= ${goFloat(p.min)}`],
    [goName(p, 'Max'), `= ${goFloat(p.max)}`],
    [goName(p, 'Default'), `= ${goFloat(p.default)}`],
  ])).map(line => `\t${line}`).join('\n');
  // Charm 的每个字段前都有一行说明注释，注释会把 gofmt 的对齐组切开 ——
  // 所以这里只按字段顺序拼，不补列宽。
  const fields = table.parameters.map(p => `\t// ${p.fieldDoc}\n\t${p.go} float64 \`yaml:"${p.key}" json:"${p.key}"\``).join('\n');
  const normalizers = table.parameters.map(p => {
    if (p.kind === 'segments' && p.key === 'segments') return `\t\t{&d.Charm.${p.go}, normalizeSegments},`;
    if (p.kind === 'segments') return `\t\t{&d.Charm.${p.go}, normalizeFpsCap},`;
    if (p.kind === 'lineWidth') return `\t\t{&d.Charm.${p.go}, normalizeLineWidth},`;
    if (p.kind === 'signed') return `\t\t{&d.Charm.${p.go}, pointerOffsetNormalizer(${goName(p, 'Min')}, ${goName(p, 'Max')}, ${goName(p, 'Default')})},`;
    if (p.kind === 'nonNegative') return `\t\t{&d.Charm.${p.go}, nonNegativeNormalizer(${goName(p, 'Min')}, ${goName(p, 'Max')}, ${goName(p, 'Default')})},`;
    return `\t\t{&d.Charm.${p.go}, positiveNormalizer(${goName(p, 'Min')}, ${goName(p, 'Max')}, ${goName(p, 'Default')})},`;
  }).join('\n');
  // 解码字面量与中间层结构体同理：Enable 与 12 个数值字段是连续的对齐组。
  const defaults = alignRows([
    ['Enable:', 'charmBoolOrDefault(decoded.Enable, true),'],
    ...table.parameters.map(p => [`${p.go}:`, `charmFloatOrDefault(decoded.${p.go}, ${goName(p, 'Default')}),`]),
  ]).map(line => `\t\t${line}`).join('\n');
  const decodeFields = alignRows([
    ['Enable', '*bool', '`json:"enable"`'],
    ...table.parameters.map(p => [p.go, '*float64', `\`json:"${p.key}"\``]),
  ]).map(line => `\t${line}`).join('\n');
  return `// Code generated by scripts/generate-deco-parameters.mjs from config/deco-charm-parameters.json; DO NOT EDIT.
//
// 这是 deco 段在后端一侧的消费物：数值事实来自仓库级参数表，
// 段名与类型仍由 #283 的段注册表（platform/config/registry.go）登记，
// 不在本文件另起一份参数事实。

package conf

import (
	"encoding/json"
	"math"
)

// 参数表生成的钳位边界与缺省回落值；注释只写语义，不改数值。
const (
${constants}
)

// Deco 是装饰配置段；契约里的区间与默认值由参数表在生成后统一注入。
type Deco struct {
	Charm Charm \`yaml:"charm" json:"charm"\`
}

type Charm struct {
	Enable bool \`yaml:"enable" json:"enable" default:"true"\`
${fields}
}

// charmDecode 是 Charm 的 JSON 解码中间层：数值字段用 *float64、开关用 *bool，
// 才能把"JSON 里没给这个键（或给了 null）"与"给了 0 / false"分开。
type charmDecode struct {
${decodeFields}
}

// UnmarshalJSON 让 null / 缺键回落到参数表生成的默认值；显式 0 与 false 原样保留。
func (c *Charm) UnmarshalJSON(data []byte) error {
	var decoded charmDecode
	if err := json.Unmarshal(data, &decoded); err != nil {
		return err
	}
	*c = Charm{
${defaults}
	}
	return nil
}

func charmFloatOrDefault(value *float64, fallback float64) float64 {
	if value == nil {
		return fallback
	}
	return *value
}

func charmBoolOrDefault(value *bool, fallback bool) bool {
	if value == nil {
		return fallback
	}
	return *value
}

// Normalize 把装饰配置收敛进参数表给出的合法范围，永不报错。
func (d Deco) Normalize() Deco {
	fields := []struct {
		ptr       *float64
		normalize func(float64) float64
	}{
${normalizers}
	}
	for _, field := range fields {
		*field.ptr = field.normalize(*field.ptr)
	}
	return d
}

func positiveNormalizer(min, max, fallback float64) func(float64) float64 {
	return func(v float64) float64 { return normalizePositiveRange(v, min, max, fallback) }
}

func nonNegativeNormalizer(min, max, fallback float64) func(float64) float64 {
	return func(v float64) float64 { return normalizeNonNegativeRange(v, min, max, fallback) }
}

func pointerOffsetNormalizer(min, max, fallback float64) func(float64) float64 {
	return func(v float64) float64 { return normalizePointerOffset(v, min, max, fallback) }
}

func normalizePositiveRange(v, min, max, fallback float64) float64 {
	if math.IsNaN(v) || math.IsInf(v, 0) {
		return fallback
	}
	if v <= 0 {
		return fallback
	}
	return math.Min(max, math.Max(min, v))
}

func normalizeNonNegativeRange(v, min, max, fallback float64) float64 {
	if math.IsNaN(v) || math.IsInf(v, 0) {
		return fallback
	}
	if v < 0 {
		return fallback
	}
	return math.Min(max, math.Max(min, v))
}

func normalizeSignedRange(v, min, max, fallback float64) float64 {
	if math.IsNaN(v) || math.IsInf(v, 0) {
		return fallback
	}
	return math.Min(max, math.Max(min, v))
}

func normalizePointerOffset(v, min, max, fallback float64) float64 {
	v = normalizeSignedRange(v, min, max, fallback)
	return math.Round(v)
}

func normalizeLineWidth(v float64) float64 {
	v = normalizePositiveRange(v, CharmLineWidthMin, CharmLineWidthMax, CharmLineWidthDefault)
	return math.Round(v*10) / 10
}

func normalizeSegments(v float64) float64 {
	if math.IsNaN(v) || math.IsInf(v, 0) {
		return CharmSegmentsDefault
	}
	if v <= 0 {
		return CharmSegmentsDefault
	}
	rounded := math.Round(v)
	return math.Min(CharmSegmentsMax, math.Max(CharmSegmentsMin, rounded))
}

func normalizeFpsCap(v float64) float64 {
	v = normalizePositiveRange(v, CharmFpsCapMin, CharmFpsCapMax, CharmFpsCapDefault)
	return math.Round(v)
}
`;
}

function yamlDecoSection(table) {
  const lines = [
    '# Generated from config/deco-charm-parameters.json by scripts/generate-deco-parameters.mjs; DO NOT EDIT.',
    '# 装饰配置只放纯装饰参数：改错了最多难看，不会让任何业务链路坏掉。',
    'deco:',
    '  charm:',
    '    # 光标挂件总开关。默认开着：上线后读者立刻就能看到，不用先去后台找。',
    '    enable: true',
  ];
  for (const p of table.parameters) {
    lines.push(`    # ${p.comment}`);
    lines.push(`    ${p.key}: ${num(p.default)}`);
  }
  return lines.join('\n');
}

function replaceGeneratedBlock(source, start, end, generated) {
  const from = source.indexOf(start);
  const to = source.indexOf(end, from);
  if (from < 0 || to < 0) throw new Error(`找不到生成区标记：${start} / ${end}`);
  let after = to + end.length;
  while (source[after] === '\r' || source[after] === '\n') after++;
  return source.slice(0, from) + generated + source.slice(after);
}

function yamlSource(source, table) {
  const start = '# Generated from config/deco-charm-parameters.json';
  const end = '# <!-- END GENERATED DECO -->';
  const from = source.indexOf(start);
  const to = source.indexOf(end, from);
  if (from < 0 || to < 0) throw new Error(`找不到生成区标记：${start} / ${end}`);
  return source.slice(0, from) + `${yamlDecoSection(table)}\n# <!-- END GENERATED DECO -->`;
}

function readerSource(source, table) {
  const constants = table.parameters.map(p => `export const ${tsReaderName(p, 'MIN')} = ${num(p.min)};\nexport const ${tsReaderName(p, 'MAX')} = ${num(p.max)};\nexport const ${tsReaderName(p, 'DEFAULT')} = ${num(p.default)};`).join('\n');
  const configKeyFor = p => ({
    RopeLength: 'ropeLengthPx', Segments: 'segments', Gravity: 'gravity', Damping: 'damping',
    Stiffness: 'stiffness', LineWidth: 'lineWidthPx', IdleSwayHz: 'idleSwayHz', IdleSwayAmp: 'idleSwayAmp',
    FpsCap: 'fpsCap', PointerOffsetX: 'pointerOffsetX', PointerOffsetY: 'pointerOffsetY',
  })[p.go];
  const fields = table.parameters
    .filter(p => p.key !== 'logo_size')
    .sort((a, b) => ['rope_length', 'segments', 'gravity', 'damping', 'stiffness', 'line_width', 'idle_sway_hz', 'idle_sway_amp', 'fps_cap', 'pointer_offset_x', 'pointer_offset_y'].indexOf(a.key) - ['rope_length', 'segments', 'gravity', 'damping', 'stiffness', 'line_width', 'idle_sway_hz', 'idle_sway_amp', 'fps_cap', 'pointer_offset_x', 'pointer_offset_y'].indexOf(b.key))
    .map(p => `  { configKey: "${configKeyFor(p)}", storeKey: "${p.key}", clamp: clampCharm${p.go} },`)
    .join('\n');
  const generated = `// Code generated by scripts/generate-deco-parameters.mjs from config/deco-charm-parameters.json; DO NOT EDIT.\n${constants}\n\nexport const CHARM_CONFIG_FIELDS = [\n${fields}\n] as const satisfies readonly CharmConfigField[];
// <!-- END GENERATED DECO -->\n`;
  return replaceGeneratedBlock(source,
    '// Code generated by scripts/generate-deco-parameters.mjs',
    '<!-- END GENERATED DECO -->', generated);
}

const decoParamTypes = `export type DecoParamKind = 'positive' | 'nonNegative' | 'signed' | 'segments' | 'lineWidth'

export interface DecoNumberParamMeta {
  key: string
  label: string
  unit: string
  hint: string
  kind: DecoParamKind
  min: number
  max: number
  step: number
  defaultValue: number
  integer?: boolean
  precision?: number
}

function defineDecoParam<Key extends string>(
  meta: Omit<DecoNumberParamMeta, 'key'> & { key: Key },
): DecoNumberParamMeta & { readonly key: Key } {
  return meta
}
`;

function adminSource(source, table) {
  const constants = table.parameters.map(p => `export const ${tsAdminName(p, 'MIN')} = ${num(p.min)}\nexport const ${tsAdminName(p, 'MAX')} = ${num(p.max)}\nexport const ${tsAdminName(p, 'DEFAULT')} = ${num(p.default)}`).join('\n');
  const params = table.parameters.map(p => {
    const optional = [
      p.integer ? '  integer: true,' : null,
      p.precision !== null && p.precision !== undefined ? `  precision: ${p.precision},` : null,
    ].filter(Boolean).join('\n');
    return `export const ${adminParamName(p)} = defineDecoParam({\n  key: '${p.key}',\n  label: '${p.label}',\n  unit: '${p.unit}',\n  hint: '${p.hint}',\n  kind: '${p.kind}',\n  min: ${tsAdminName(p, 'MIN')},\n  max: ${tsAdminName(p, 'MAX')},\n  step: ${num(p.step)},\n  defaultValue: ${tsAdminName(p, 'DEFAULT')},${optional ? `\n${optional}` : ''}\n})`;
  }).join('\n\n');
  const list = table.parameters.map(p => `  ${adminParamName(p)},`).join('\n');
  const generated = `/**\n * 装饰（光标挂件）参数的元数据与钳位。\n *\n * 数值事实由 config/deco-charm-parameters.json 生成；本文件只保留后台侧的\n * 行为规则与表单文案。重新生成后四端无差异 + 运行时取值正确由一条校验守住。\n */\n\n// Code generated by scripts/generate-deco-parameters.mjs from config/deco-charm-parameters.json; DO NOT EDIT.\n${decoParamTypes}\n${constants}\n\n${params}\n\nexport const DECO_NUMBER_PARAMS = [\n${list}\n] as const\n// <!-- END GENERATED DECO -->\n`;
  return replaceGeneratedBlock(source,
    '/**\n * 装饰（光标挂件）参数的元数据与钳位。',
    '<!-- END GENERATED DECO -->', generated);
}

function contractProperties(root, table) {
  const doc = JSON.parse(fs.readFileSync(path.join(root, 'backend/docs/swagger.json'), 'utf8'));
  const properties = doc.components?.schemas?.['conf.Charm']?.properties || {};
  for (const p of table.parameters) {
    const property = properties[p.key];
    if (!property) throw new Error(`契约缺少 conf.Charm.${p.key}`);
    for (const [field, want] of [['minimum', p.min], ['maximum', p.max], ['default', p.default]]) {
      if (property[field] !== want) throw new Error(`契约 conf.Charm.${p.key}.${field} 应为 ${want}，实际 ${property[field]}`);
    }
  }
}

function runtimeValues(root, table) {
  const go = spawnSync('go', ['test', '-count=1', './internal/site/adapter/http/', '-run', 'TestGeneratedDecoParametersAreExposedByContractAndHTTP'], {
    cwd: path.join(root, 'backend'), encoding: 'utf8', maxBuffer: 10 * 1024 * 1024,
  });
  if (go.status !== 0) throw new Error(`运行时取值/HTTP 行为校验失败：\n${(go.stdout || '') + (go.stderr || '')}`);
}

const opts = args(process.argv.slice(2));
const root = opts.root;
const table = JSON.parse(fs.readFileSync(path.join(root, 'config/deco-charm-parameters.json'), 'utf8'));
if (table.section !== 'deco' || table.subsection !== 'charm' || table.parameters.length !== 12) {
  throw new Error('参数表必须描述 deco.charm 的 12 个数值参数');
}

const rawOutputs = [
  ['backend/conf/conf_deco.go', backendSource(table)],
  ['backend/config/site_default_settings.yaml', yamlSource(fs.readFileSync(path.join(root, 'backend/config/site_default_settings.yaml'), 'utf8'), table)],
  ['frontend/app/utils/decoCharm.ts', readerSource(fs.readFileSync(path.join(root, 'frontend/app/utils/decoCharm.ts'), 'utf8'), table)],
  ['frontend_admin/app/utils/decoParams.ts', adminSource(fs.readFileSync(path.join(root, 'frontend_admin/app/utils/decoParams.ts'), 'utf8'), table)],
];

const outputs = rawOutputs;

if (opts.check) {
  const stale = [];
  for (const [rel, generated0] of outputs) {
    const generated = generated0;
    const actual = fs.readFileSync(path.join(root, rel), 'utf8');
    if (actual !== generated) {
      fs.writeFileSync(path.join(os.tmpdir(), `286-expected-${path.basename(rel)}`), generated);
      stale.push(rel);
    }
  }
  if (stale.length) {
    console.error(`✗ 重新生成后四端有差异：${stale.join(' / ')}`);
    process.exit(1);
  }
  try {
    contractProperties(root, table);
    runtimeValues(root, table);
  } catch (e) {
    console.error(`✗ 运行时取值正确校验失败：${e.message}`);
    process.exit(1);
  }
  console.log('✓ 重新生成后四端无差异 + 运行时取值正确（契约/HTTP 同批校验）');
} else {
  for (const [rel, generated] of outputs) {
    fs.writeFileSync(path.join(root, rel), generated);
    console.log(`generated ${rel}`);
  }
  console.log('契约（开放接口契约）由 make openapi 生成后，再用 scripts/decorate-deco-contract.mjs 从同一参数表注入 min/max/default。');
}
