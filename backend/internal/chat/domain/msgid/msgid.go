// Package msgid 是「幂等键 → 消息主键」派生规则的具名模块（#279）。
//
// 私信的发送幂等靠零 DDL 的一条巧劲：把（发送人，客户端幂等键）导出成一个
// **确定性的消息主键**，重复提交就会在 INSERT 时撞主键，由数据库保证
// "重复提交不产生第二条消息"，进程崩溃与多实例并发都不影响。
//
// 这条规则过去写在 domain 的通用文件里，和会话 ID、摘要、陌生人判定混在一起，
// 于是"它到底会不会影响排序"要靠读实现才知道。现在它是一个具名模块：
//
//   - 对外只有 FromClientKey 一个入口，号段与哈希算法都是实现细节；
//   - 号段与正常消息主键不相交（雪花 ID 远小于保留区间），所以派生消息
//     既不撞普通消息，反之亦然；
//   - **派生主键的大小与消息先后无关**。因此排序、水位、分页一律不读 ID
//     大小，只把它当作"同一时刻的确定性并列裁决 / 扫描游标"。
//     这条约束写在 ADR-0016 里（读取路径与号段），不是本包的私有约定。
package msgid

import (
	"hash/fnv"

	"myblogx/internal/kernel/ctype"
)

// clientKeyIDBase 是派生主键保留区间的下界（2^62）。
//
// 雪花 ID 在可预见的年份里都远小于 2^62（纪元 2024、41 位毫秒要到 2058 年
// 才逼近上界），因此 [2^62, 2^63) 与正常消息主键不相交。
//
// 不导出：调用方只问"这条幂等键对应哪个主键"，不该关心号段。
const clientKeyIDBase uint64 = 1 << 62

// FromClientKey 由（发送人，客户端幂等键）导出确定性的消息主键。
//
// 为什么不用"幂等键查重表"：零 DDL 不能给 chat_msg_models 加列、也不新增表。
// 把幂等键映射到主键上，重复提交就会撞主键 —— 幂等性由数据库的唯一约束保证，
// 而不是靠应用层的"先查再写"（那在并发下必然漏）。
//
// 键里带发送人：两个用户用同一个客户端键（浏览器里都是 "1"）不能互相吞消息。
func FromClientKey(sender ctype.ID, key string) ctype.ID {
	h := fnv.New64a()
	_, _ = h.Write([]byte("chat:" + sender.String() + "\x00" + key))
	return ctype.NewID((h.Sum64() & (clientKeyIDBase - 1)) | clientKeyIDBase)
}
