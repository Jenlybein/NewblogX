package review

import "fmt"

// 放行留痕 = "管理员以 X 分放行（放行线 Y 分）"。
//
// # 为什么要有这句话
//
// 管理员点"通过"时**豁免质量闸门**（管理员是终审，强制卡他会让紧急放行失效）。
// 豁免不等于没有发生过：事后复盘要能回答"当时这篇文章多少分、放行线是多少"，
// 否则"越级放行"和"正常放行"在库里长得一模一样，追责与调参都无从下手。
// 所以通过与驳回各留各的痕：驳回的意见进 reason，放行的这句话进 approve_note。
//
// # 为什么 nil 与 0 分必须写成不同的话
//
// 分数取不到有几种原因：AI 没开、文章还没评分、模型调用失败、端口没装配。
// 这些情况下拿不到分数，与**模型评了、结果就是 0 分**是两件事：前者说不了
// 这篇文章到底多差，后者是有结论的"最差"。合并成"0 分"会让复盘误以为模型
// 真的给过 0 分。所以 nil 写成"未知分数"，0 分老实写成"以 0 分放行"。
//
// 放行线即便闸门关闭也照写：它是这次放行时**生效配置**的算出值
// （及格线 + 灰带宽度），只用于展示，不参与判定；写进备注才能让"当时的线"
// 与"现在的线"分开。格式固定，前端与日志都按这句话找，不要改字面。
func FormatApproveNote(score *int, passLine int) string {
	if score == nil {
		return fmt.Sprintf("管理员以未知分数放行（放行线 %d 分）", passLine)
	}
	return fmt.Sprintf("管理员以 %d 分放行（放行线 %d 分）", *score, passLine)
}
